/**
 * What a European household plausibly owns and bothers to catalogue, with the
 * facts that keep every other field honest: list price (EUR, French market at
 * launch), release month (nothing is bought before it exists), where in a
 * home it lives, whether it carries a serial number, how long its warranty
 * usually runs, whether it comes in sets, and whether people lend it.
 *
 * Category defaults cover most of that; an item overrides only where its
 * category would lie (a watch is jewellery but has a serial and goes to a
 * watchmaker; dining chairs are furniture but come in sixes).
 */
import type { Prisma } from "@prisma/client";

export type Category = NonNullable<Prisma.ArticleCreateManyInput["category"]>;

export type RoomKey =
  | "living"
  | "dining"
  | "kitchen"
  | "bedroom"
  | "kids"
  | "guest"
  | "office"
  | "dressing"
  | "bathroom"
  | "laundry"
  | "entry"
  | "cellar"
  | "garage"
  | "attic"
  | "shed"
  | "garden"
  | "balcony"
  | "safe";

export type BundleKey =
  | "office"
  | "camera"
  | "ski"
  | "workshop"
  | "kitchen"
  | "baby"
  | "hifi";

export type FieldKey =
  | "storage"
  | "colour"
  | "size"
  | "frame"
  | "material"
  | "dimensions"
  | "energy"
  | "strings";

export interface Noun {
  fr: string;
  en: string;
}

export interface CatalogItem {
  key: string;
  category: Category;
  brand: string;
  /** As the maker or a French shop lists it. */
  name: string;
  /** As a UK shop lists it, where that differs. */
  nameEn?: string;
  /** What people call it when they don't type the product name. */
  noun: Noun;
  /** The reference people copy from the box or the invoice. */
  model: string;
  /** List price in EUR at launch. */
  price: number;
  /** Annual straight-line depreciation, %. */
  dep: number;
  /** YYYY-MM. Not purchasable before this. */
  released?: string;
  rooms?: RoomKey[];
  /** Warranty length options, months. */
  warranty?: number[];
  serial?: boolean;
  /** Sold or owned as a set, e.g. dining chairs. */
  units?: [number, number];
  /** A household plausibly owns one per person. */
  perPerson?: boolean;
  lendable?: boolean;
  serviceable?: boolean;
  /** Odds it was bought second-hand. */
  secondHand?: number;
  /** Needs a house (garden, garage) to make sense. */
  house?: boolean;
  /** Only with children at home. */
  kids?: boolean;
  /** Small enough to lose. */
  portable?: boolean;
  bundle?: BundleKey;
  fields?: FieldKey[];
  /** The colours it was actually sold in (French, English). Required with a
   *  "colour" field; one entry when the model number pins the colour. */
  colours?: { fr: string[]; en: string[] };
}

interface CategoryDefaults {
  rooms: RoomKey[];
  warranty: number[];
  serial: boolean;
  lendable: boolean;
  serviceable: boolean;
  secondHand: number;
  /** Months a model is typically still sold new after release. */
  shelfLifeMonths: number | null;
}

